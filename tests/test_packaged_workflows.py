"""Exercise extracted skill packages against synthetic venture inputs."""

import csv
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest
from zipfile import ZipFile

from _load import FIX, ROOT
from test_market import BOTTOM, SOM, TOP

TODAY = "2026-10-26"
FIXTURES = Path(FIX)


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


class PackagedWorkflows(unittest.TestCase):
    def run_script(self, cwd, script, *args):
        result = subprocess.run(
            [sys.executable, str(script), *map(str, args)],
            cwd=cwd, capture_output=True, text=True, encoding="utf-8", timeout=30,
        )
        self.assertEqual(result.returncode, 0, f"{script.name} {args}\n{result.stdout}{result.stderr}")
        return result.stdout

    def test_all_extracted_skills_generate_synthetic_outputs(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            archives = root / "archives"
            installed = root / "installed"
            self.run_script(root, Path(ROOT) / "scripts/skills.py", "package", "--output", archives)
            for path in sorted(archives.glob("*.zip")):
                # Consume archives generated by the in-tree allowlist, never external input.
                with ZipFile(path) as bundle:
                    bundle.extractall(installed)

            def skill(cwd, name, *args):
                folder = installed / f"seed-{name}"
                cwd.mkdir(exist_ok=True)
                self.assertTrue((folder / "references/workflow.md").is_file())
                return self.run_script(cwd, next(folder.glob("*.py")), *args)

            market = root / "market"
            for args in (TOP, BOTTOM, SOM):
                skill(market, "market", *args, "--write", "--today", TODAY)
            sized = read_json(market / "seed/market.json")
            self.assertEqual([sized[k] for k in ("tam", "sam", "som")], [17040000000, 960000000, 24000000])

            scout = root / "scout"
            skill(scout, "scout", "compare", 1900000101, 1900000202,
                  "--offline", FIXTURES / "seed-scout", "--today", TODAY, "--write")
            compared = read_json(scout / "seed/competitors.json")
            self.assertEqual([app["low_reviews"] for app in compared["apps"]], [24, 20])

            venture = root / "venture"
            records = venture / "seed"
            shutil.copytree(FIXTURES / "seed-plan/leashly", records)
            skill(venture, "model", "init")
            skill(venture, "model", "run", "--write")
            skill(venture, "model", "csv")
            with (records / "model.csv").open(newline="", encoding="utf-8") as stream:
                self.assertEqual(len(list(csv.reader(stream))), 37)
            self.assertEqual(read_json(records / "model.json"),
                             read_json(FIXTURES / "seed-plan/leashly/model.json"))
            skill(venture, "plan", "build", "--today", TODAY)
            self.assertGreater((records / "plan.md").stat().st_size, 1000)
            skill(venture, "deck", "build")
            self.assertGreater((records / "deck.html").stat().st_size, 1000)

            skill(venture, "investors", "import", installed / "seed-investors/investors.example.csv",
                  "--today", TODAY)
            skill(venture, "investors", "rank", "--stage", "seed", "--sectors",
                  "pet care; marketplaces; local services; consumer", "--geo", "US", "--ask", "1.5M",
                  "--today", TODAY, "--write")
            ranked = read_json(records / "investors.json")
            self.assertEqual([row["fit"] for row in ranked["investors"]], [96, 93, 91, 89, 87, 85])

            outreach = root / "outreach-inputs"
            shutil.copytree(FIXTURES / "seed-closer", outreach)
            skill(venture, "closer", "draft", "--dir", outreach, "--ids", "maya-chen", "--today", TODAY)
            self.assertIn(b"maya@northlight.example", (outreach / "outreach/maya-chen-1.eml").read_bytes())
            preview = json.loads(skill(venture, "closer", "batch", "--dir", outreach, "--today", TODAY, "--json"))
            self.assertEqual([item["id"] for item in preview["messages"]], ["maya-chen"])

            skill(venture, "coach", "drill", "--n", 3, "--write")
            self.assertGreater((records / "coach/drill.md").stat().st_size, 100)
            skill(venture, "terms", "safe", "--investment", "500k", "--cap", "10m", "--write")
            self.assertEqual(read_json(records / "terms/safe.json")["ownership_at_cap"], 0.05)
            skill(venture, "dataroom", "init")
            skill(venture, "dataroom", "index", "--today", TODAY)
            self.assertGreater((records / "dataroom/INDEX.md").stat().st_size, 100)
            skill(venture, "updates", "init")
            skill(venture, "updates", "write", "--month", "2026-11")
            self.assertIn("9.8 months", (records / "updates/2026-11.md").read_text(encoding="utf-8"))
